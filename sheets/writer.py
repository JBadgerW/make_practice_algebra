"""Typst for a sheet: every version's worksheet, each with its answer key after it,
in one document, and every version's slide deck in another.

The worksheet follows templates/refined_template.typ: the header, the
sheet's instructions block, then for each section a section-head (when it
has a title) and one #grid per row of problems (see sheet.rows).

A warm-up (templates/warmup_template.typ) is one half-page copy printed twice
side by side, with its answers shuffled and lettered on the back.
"""
import random
from . import banks
from .sheet import items, problem, rows
from .typst import sheet_head, slhead, warmup_head, vars_, esc, tstr

def _content(text):
    return f"[{esc(text)}]"

def _preambles(sheet):
    """Typst definitions the sheet's banks need (a bank's PREAMBLE), each once."""
    out = []
    for sec in sheet["sections"]:
        for it in sec["items"]:
            pre = getattr(banks.get(it["bank"]), "PREAMBLE", "")
            if pre and pre not in out:
                out.append(pre)
    return "".join(pre + "\n" for pre in out)

# A bookmark in the PDF's sidebar, taking no room on the page.
BOOKMARK = "#let bookmark(t, level: 1) = place(hide(heading(level: level, outlined: false, bookmarked: true, t)))\n"

def _key_prompt(b, p, gap="0.3em"):
    """The prompt as the key shows it: a bank may draw on it (key_typst), as when a graph is the answer."""
    return getattr(b, "key_typst", b.typst)(p, gap)

def _question(it, v, key, space=None):
    b = banks.get(it["bank"])
    p = problem(it, v)
    # The answer floats in the work space, so the key breaks pages where the sheet does.
    ans = b.answer_typst(p) if key else ""
    a = f"\n    #place(right, dy: 0.5em)[#text(fill: red)[{ans}] #h(0.4em)]" if ans else ""
    return f"  question(space-below: {space or it['space']})[\n    {_key_prompt(b, p) if key else b.typst(p)}{a}\n  ],\n"

def _body(sheet, v, key):
    """The worksheet (or its key) after the preamble: the header, then each section."""
    title = sheet["title"] + (" — Answer Key" if key else "")
    s = f"#first-page-header(class-name, {tstr(title)}, version: {tstr(str(v + 1))})\n"
    if sheet["instructions"]:
        s += f"#instructions-block({_content(sheet['instructions'])})\n"
    for sec in sheet["sections"]:
        if not sec["items"]:
            continue
        s += "\n" if s.endswith(")\n") else ""
        if sec["title"]:
            ins = f"(instructions: {_content(sec['instructions'])})" if sec["instructions"] else ""
            s += f"#section-head{ins}{_content(sec['title'])}\n"
        elif sec["instructions"]:
            s += f"#instructions-block({_content(sec['instructions'])})\n"
        for row in rows(sec["items"]):
            cols = "  columns: (1fr, 1fr),\n  column-gutter: 1em,\n" if row[0]["width"] == "half" else ""
            s += "#grid(\n" + cols + "".join(_question(it, v, key) for it in row) + ")\n\n"
    return s.rstrip("\n") + "\n"

def worksheet(sheet, v=0, key=False, with_key=False):
    """Typst for version v (0-based) of the sheet, or its answer key alone; with_key
    appends the key to the sheet, on a page of its own and numbered from 1 again."""
    s = (f"// Generated by: {sheet['command']}\n" if sheet.get("command") else "")
    s += sheet_head + vars_(sheet["title"], str(v + 1), sheet["class_name"]) + _preambles(sheet)
    s += _body(sheet, v, key)
    if with_key:
        s += "\n#pagebreak()\n#qnum.update(0)\n" + _body(sheet, v, True)
    return s

def worksheets(sheet):
    """Typst for every version of the sheet, each followed by its key, in one
    document: each starts on a new page, numbered from 1, with a bookmark."""
    s = (f"// Generated by: {sheet['command']}\n" if sheet.get("command") else "")
    s += sheet_head + vars_(sheet["title"], "1", sheet["class_name"]) + _preambles(sheet) + BOOKMARK
    for v in range(sheet["versions"]):
        if v:
            s += "\n#pagebreak()\n#qnum.update(0)\n"
        s += f"#bookmark[Version {v + 1}]\n" + _body(sheet, v, False)
        s += f"\n#pagebreak()\n#qnum.update(0)\n#bookmark[Version {v + 1} Key]\n" + _body(sheet, v, True)
    return s

def unlettered(sheet):
    """How many of a warm-up's problems have no answer to letter (a graph is the answer)."""
    return sum(not banks.get(it["bank"]).answer_typst(problem(it)) for it in items(sheet))

def warmup(sheet):
    """Typst for the half-page warm-up: the front holds the sheet twice, every
    problem in one run (section titles don't print) with the work space shared
    evenly; the back holds its answers twice, shuffled (the same problems
    always shuffle the same way) and lettered."""
    s = (f"// Generated by: {sheet['command']}\n" if sheet.get("command") else "")
    s += sheet_head + warmup_head + "\n" + vars_(sheet["title"], "1", sheet["class_name"]) + _preambles(sheet)
    body = ""
    for row in rows(items(sheet)):
        cols = "  columns: (1fr, 1fr),\n  column-gutter: 1em,\n" if row[0]["width"] == "half" else ""
        body += "#grid(\n" + cols + "".join(_question(it, 0, False, space="0pt") for it in row) + ")\n#v(1fr)\n"
    ins = f", instructions: {_content(sheet['instructions'])}" if sheet["instructions"] else ""
    s += f"#let front = warmup-half(class-name, worksheet-title{ins})[\n{body}]\n#two-up(front)\n"
    probs = [(banks.get(it["bank"]), problem(it)) for it in items(sheet)]
    answers = [a for b, p in probs if (a := b.answer_typst(p))]
    random.Random("|".join(b.typst(p) for b, p in probs)).shuffle(answers)
    s += "\n#pagebreak()\n#let back = answer-half(worksheet-title, (\n"
    s += "".join(f"  [{a}],\n" for a in answers) + "))\n#two-up(back)\n"
    return s

def _section_slide(sec):
    """The title slide for a section: a type's hints when the section is all one
    type, every type's hints when it mixes types of one bank, else just its title."""
    bs = [banks.get(it["bank"]) for it in sec["items"]]
    if len({b.FAMILY for b in bs}) == 1:
        hints = list(dict.fromkeys(b.hint(b.type_of(it["entry"])) for b, it in zip(bs, sec["items"])))
        if None not in hints:
            if len(hints) == 1:
                lbl, ttl, look, move = hints[0]
                b, t = bs[0], bs[0].type_of(sec["items"][0]["entry"])
                name = ttl if sec["title"] == b.heading(t) else esc(sec["title"])
                return f"#pagebreak()\n#type-slide([{lbl}], [{name}], [{look}], [{move}])\n"
            items = ", ".join("([{}], [{}], [{}], [{}])".format(*h) for h in hints)
            return f"#pagebreak()\n#group-slide({_content(sec['title'])}, ({items}))\n"
    return f"#pagebreak()\n#group-slide({_content(sec['title'])}, ())\n"

def slides(sheet, v=None):
    """Typst for the slide deck of version v (0-based), or with v None every
    version's deck in one document: a contents slide linking to each when there
    are several, and a bookmark for each version and its sections."""
    titled = [sec for sec in sheet["sections"] if sec["title"] and sec["items"]]
    most = max([len({(banks.get(it["bank"]).FAMILY, banks.get(it["bank"]).type_of(it["entry"]))
                     for it in sec["items"]}) for sec in titled] or [0])
    s = (f"// Generated by: {sheet['command']}\n" if sheet.get("command") else "")
    vs = [v] if v is not None else list(range(sheet["versions"]))
    s += slhead + vars_(sheet["title"], str(vs[0] + 1), sheet["class_name"]) + _preambles(sheet) + BOOKMARK + f"""
// The problem (and answer) at 24pt, smaller only if that won't fit on the slide:
// one problem per slide, never spilling onto the next. A short problem sits
// centered; a word problem fills the width, left-aligned.
#let slide(n, prob, answer: none) = {{
  align(left)[#text(size: 30pt, weight: "bold")[Problem #n]]
  v(1em)
  block(width: 100%, height: 1fr, layout(room => {{
    let body(s) = align(center, box(align(left, text(size: s, {{
      prob
      if answer != none {{
        v(0.8em)
        text(fill: red, answer)
      }}
    }}))))
    let s = 24pt
    while s > 8pt and measure(body(s), width: room.width).height > room.height {{
      s -= 1pt
    }}
    body(s)
  }}))
}}

#let type-slide(lbl, title, look, move) = align(horizon)[
  #text(size: 24pt, fill: luma(90))[#lbl]
  #v(-0.3em)
  #text(size: 40pt, weight: "bold")[#title]
  #v(0.6em)
  #text(size: 24pt)[*Look for:* #look]
  #v(0.2em)
  #text(size: 24pt)[*The move:* #move]
]

#let group-slide(heading, items) = align(horizon)[
  #text(size: 40pt, weight: "bold")[#heading]
  #v(0.5em)
  #for it in items [
    #text(size: {20 if most <= 4 else 17}pt)[*#it.at(0): #it.at(1)* #h(0.4em) _Look for:_ #it.at(2) #h(0.4em) _The move:_ #it.at(3)]
    #v(0.35em)
  ]
]
"""
    if len(vs) > 1:
        links = "".join(f"  #link(<version-{w + 1}>)[#text(size: 30pt, fill: blue)[Version {w + 1}]]\n  #v(0.3em)\n" for w in vs)
        s += f"""
#align(center + horizon)[
  #text(size: 44pt, weight: "bold")[#worksheet-title]
  #v(0.6em)
{links}]
"""
    for i, w in enumerate(vs):
        s += _deck(sheet, w, start=not (i or len(vs) > 1), bookmark=v is None)
    return s

def _deck(sheet, v, start, bookmark):
    """Version v's slides: its title slide (opening the document when start),
    then each section's title slide and each problem's question and answer slides."""
    s = "" if start else "\n#pagebreak()\n"
    s += f"""#bookmark[Version {v + 1}] <version-{v + 1}>\n""" if bookmark else ""
    s += f"""#align(center + horizon)[
  #text(size: 44pt, weight: "bold")[#worksheet-title]
  #v(0.4em)
  #text(size: 28pt)[Version {v + 1}]
  #v(0.2em)
  #text(size: 24pt){_content(sheet["instructions"])}
]
"""
    n = 0
    for sec in sheet["sections"]:
        if not sec["items"]:
            continue
        if sec["title"]:
            s += _section_slide(sec)
            s += f"#bookmark(level: 2)[{esc(sec['title'])}]\n" if bookmark else ""
        for it in sec["items"]:
            n += 1
            b, p = banks.get(it["bank"]), problem(it, v)
            pr, ans = b.typst(p, gap="0.5em"), b.answer_typst(p)
            s += f"#pagebreak()\n#slide({n}, [{pr}])\n"
            s += f"#pagebreak()\n#slide({n}, [{_key_prompt(b, p, '0.5em')}], answer: {f'[{ans}]' if ans else 'none'})\n"
    return s
